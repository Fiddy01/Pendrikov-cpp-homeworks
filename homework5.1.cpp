#include <iostream> // Для ввода/вывода (cin, cout)
#include <bitset>   // Для удобного отображения чисел в двоичном виде (опционально, для понимания)

int main() {
    int num1, num2; // Переменные для двух целых чисел

    // Запрашиваем первое число
    std::cout << "Введите первое число: ";
    std::cin >> num1;

    // Запрашиваем второе число
    std::cout << "Введите второе число: ";
    std::cin >> num2;

    // --- Выполняем и выводим результаты побитовых операций ---

    // 1. Побитовое И (AND)
    // Оператор: &
    // Бит результата равен 1, только если оба соответствующих бита операндов равны 1.
    int result_and = num1 & num2;
    std::cout << "Результат побитового AND: " << result_and << std::endl;

    // 2. Побитовое ИЛИ (OR)
    // Оператор: |
    // Бит результата равен 1, если хотя бы один из соответствующих битов операндов равен 1.
    int result_or = num1 | num2;
    std::cout << "Результат побитового OR: " << result_or << std::endl;

    // 3. Побитовое Исключающее ИЛИ (XOR)
    // Оператор: ^
    // Бит результата равен 1, если соответствующие биты операндов РАЗЛИЧАЮТСЯ (один 0, другой 1).
    int result_xor = num1 ^ num2;
    std::cout << "Результат побитового XOR: " << result_xor << std::endl;

    return 0; // Программа успешно завершена
}