#include <iostream> // Для ввода/вывода (cin, cout)

int main() {
    int n; // Верхняя граница диапазона

    // Запрашиваем у пользователя число N
    std::cout << "Введите N: ";
    std::cin >> n;

    // Выводим заголовок перед списком чётных чисел
    std::cout << "Чётные числа от 1 до " << n << ":" << std::endl;

    // --- Использование цикла for для перебора чисел ---
    // Мы начнем с первого чётного числа (2) и будем увеличивать счетчик на 2 каждый раз.
    // Это самый простой и эффективный способ получить только чётные числа.
    for (int i = 2; i <= n; i = i + 2) {
        std::cout << i << " "; // Выводим текущее чётное число, добавляя пробел после него
    }
    std::cout << std::endl; // Переходим на новую строку после вывода всех чётных чисел

    return 0; // Программа успешно завершена
}