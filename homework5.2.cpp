#include <iostream> // Для ввода/вывода (cin, cout)

int main() {
    int score; // Переменная для хранения количества баллов

    // Запрашиваем у пользователя количество баллов
    std::cout << "Введите количество баллов: ";
    std::cin >> score;

    std::string grade; // Переменная для хранения итоговой оценки (текстом)

    // --- Проверяем баллы и присваиваем оценку с помощью if-else if-else ---

    // Проверяем диапазон 80-100 (отлично)
    if (score >= 80 && score <= 100) {
        grade = "Отлично";
    }
    // Проверяем диапазон 60-80 (хорошо)
    else if (score >= 60 && score < 80) { // Обрати внимание: < 80, чтобы не пересекаться с "Отлично"
        grade = "Хорошо";
    }
    // Проверяем диапазон 40-60 (удовлетворительно)
    else if (score >= 40 && score < 60) { // Обрати внимание: < 60
        grade = "Удовлетворительно";
    }
    // Проверяем диапазон 0-40 (неудовлетворительно)
    // Можно просто написать score >= 0, если у нас нет отрицательных баллов
    else if (score >= 0 && score < 40) {
        grade = "Неудовлетворительно";
    }
    // Если введенное число выходит за пределы допустимого диапазона (например, отрицательное или > 100)
    else {
        grade = "Некорректный ввод баллов";
    }

    // Выводим итоговую оценку
    std::cout << "Оценка: " << grade << std::endl;

    return 0; // Программа успешно завершена
}