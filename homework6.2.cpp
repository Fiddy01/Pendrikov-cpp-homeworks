#include <iostream> // Подключаем библиотеку для ввода/вывода

int main() {
    // Определяем размеры массива
    const int rows = 2; // Количество строк
    const int cols = 3; // Количество столбцов

    // Объявляем двумерный массив
    int array[rows][cols];

    // Переменная для заполнения массива числами
    int counter = 1;

    // Заполняем массив числами от 1 до 6
    for (int i = 0; i < rows; ++i) { // Проходим по строкам
        for (int j = 0; j < cols; ++j) { // Проходим по столбцам
            array[i][j] = counter; // Присваиваем текущее значение счетчика элементу массива
            counter++; // Увеличиваем счетчик
        }
    }

    // Выводим элементы массива в виде таблицы
    std::cout << "Элементы массива:" << std::endl; // Заголовок
    for (int i = 0; i < rows; ++i) { // Проходим по строкам
        for (int j = 0; j < cols; ++j) { // Проходим по столбцам
            std::cout << array[i][j] << " "; // Выводим элемент массива и пробел
        }
        std::cout << std::endl; // Переходим на новую строку после каждой строки массива
    }

    return 0; // Возвращаем 0, чтобы показать, что программа завершилась успешно
}