#include <iostream> // Для ввода/вывода (cout, cin)
#include <vector>   // Для использования динамического массива (vector)
#include <random>   // Для генерации случайных чисел
#include <algorithm> // Для функции max_element (или можно написать свой цикл)
#include <ctime>     // Для инициализации генератора случайных чисел

int main() {
    // --- Шаг 1: Создаем динамический массив (вектор) из 5 целых чисел ---
    std::vector<int> numbers(5);

    // --- Шаг 2: Инициализируем генератор случайных чисел ---
    std::srand(static_cast<unsigned int>(std::time(0))); 

    // --- Шаг 3: Заполняем массив случайными значениями ---
    std::cout << "Элементы массива:" << std::endl;
    for (int i = 0; i < numbers.size(); ++i) {
        // Генерируем случайное число, например, в диапазоне от 1 до 100
        // rand() % 100 + 1 дает случайное число от 1 до 100
        numbers[i] = std::rand() % 100 + 1; 
        std::cout << numbers[i] << (i == numbers.size() - 1 ? "" : " "); // Выводим число и пробел, кроме последнего
    }
    std::cout << std::endl; // Переходим на новую строку после вывода массива

    // --- Шаг 4: Определяем наибольший элемент массива ---
    // Способ 1: Используем готовую функцию из <algorithm>
    // max_element возвращает итератор на максимальный элемент
    int max_element = *std::max_element(numbers.begin(), numbers.end());

    // --- Шаг 5: Выводим найденный максимум ---
    std::cout << "Максимальный элемент: " << max_element << std::endl;

    return 0; // Программа успешно завершена
}